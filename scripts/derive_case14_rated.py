"""Regenerate ``src/mambo_power/cases/data/derived/case14_rated.m`` from ``case14.m``.

The derivation rule (``derived/PROVENANCE.md``): every ``mpc.branch`` row's ``RATE_A`` becomes
``round(max(1.2 * |base-case DC flow|, 30), 1)`` MVA — 20 % of headroom above the flow the
unmodified case14 carries on that branch, floored at 30 MVA so a lightly loaded branch is not
given a near-zero rating. Every other byte of the mpc matrices is unchanged.

Run from the repository root: ``uv run --frozen python scripts/derive_case14_rated.py``.
``tests/unit/test_fixtures_derived.py`` is the contract that the committed file obeys the rule.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

from mambo_power.io import matpower
from mambo_power.numerics import NetworkArrays
from mambo_power.pf import dc as pfdc

DATA = Path(__file__).resolve().parents[1] / "src" / "mambo_power" / "cases" / "data"
BASE = DATA / "case14.m"
TARGET = DATA / "derived" / "case14_rated.m"
MARGIN = 1.2
FLOOR_MVA = 30.0
RATE_A_COL = 5  # 0-based position of RATE_A in an mpc.branch row

HEADER = """\
function mpc = case14_rated
%CASE14_RATED    SYNTHETIC variant of case14 for the N-1 and OPF teaching material (ADR-015).
%   NOT upstream data. Derived from mambo_power/cases/data/case14.m (verbatim MATPOWER
%   file, sha256 recorded in ../PROVENANCE.md) by editing exactly the cells listed
%   below; every other byte of the mpc matrices is unchanged. Row numbers are
%   1-based positions in the matrix; column names are the MATPOWER idx_* names.
%   See derived/PROVENANCE.md for the derivation rule and tests/unit/
%   test_fixtures_derived.py for the check that enforces it.
%
%   mpc.branch rows 1-20, RATE_A: 0 -> round(max(1.2 * |P_base|, 30), 1), where P_base is
%       the branch's from-side flow in the unmodified case14's DC power flow (MW, system
%       base 100 MVA). 20 % of headroom above the base-case flow, floored at 30 MVA.
%       case14 as shipped has RATE_A == 0 on every branch (MATPOWER's "unlimited"), so
%       nothing in it can bind an OPF flow limit or an N-1 screen; this variant can.
%       Regenerated by scripts/derive_case14_rated.py; the values are:
{values}
%   All other columns, mpc.bus, mpc.gen and mpc.gencost untouched.
%
%   ----- original case14 header follows -----
"""


def ratings_mva(base: Path) -> list[float]:
    """The 20 ``RATE_A`` values the rule derives from *base*'s DC flow, in branch row order."""
    arr = NetworkArrays.from_network(matpower.load(base))
    flow_mw = np.abs(pfdc.solve(arr).p_from_pu) * arr.base_mva
    return [round(max(MARGIN * float(f), FLOOR_MVA), 1) for f in flow_mw]


def derive(base: Path) -> str:
    """The derived file's text: new header, then case14 with its ``RATE_A`` column rewritten."""
    text = base.read_text(encoding="utf-8")
    first_line, rest = text.split("\n", 1)
    assert first_line == "function mpc = case14"
    values = ratings_mva(base)
    lines = rest.split("\n")
    start = lines.index("mpc.branch = [") + 1
    for row, rating in enumerate(values):
        fields = lines[start + row].split("\t")
        assert fields[RATE_A_COL + 1] == "0", lines[start + row]  # leading tab -> offset by one
        fields[RATE_A_COL + 1] = f"{rating:g}"
        lines[start + row] = "\t".join(fields)
    assert lines[start + len(values)] == "];"
    listed = "\n".join(
        f"%       row {row + 1:2d} ({fields[0]:>2s}-{fields[1]:<2s}): {rating:g}"
        for row, rating in enumerate(values)
        for fields in [lines[start + row].strip().split("\t")]
    )
    header = HEADER.format(values=listed)
    return header + "\n".join(lines)


if __name__ == "__main__":
    TARGET.write_text(derive(BASE), encoding="utf-8", newline="\n")
    print(f"wrote {TARGET}")
